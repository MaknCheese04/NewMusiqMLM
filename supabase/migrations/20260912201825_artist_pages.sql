create table public.song_rating_totals (
  track_key text primary key,
  rating_count integer not null check (rating_count >= 0),
  rating_sum integer not null check (rating_sum >= 0)
);
alter table public.song_rating_totals enable row level security;
create policy "Read song rating totals" on public.song_rating_totals for select to authenticated using (true);
grant select on public.song_rating_totals to authenticated;

create function private.update_song_rating_totals() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'UPDATE' and new.track_key = old.track_key then
    update public.song_rating_totals set rating_sum = rating_sum + new.rating - old.rating
    where track_key = new.track_key;
    return new;
  end if;
  if tg_op in ('UPDATE', 'DELETE') then
    update public.song_rating_totals
    set rating_count = rating_count - 1, rating_sum = rating_sum - old.rating
    where track_key = old.track_key;
    delete from public.song_rating_totals where track_key = old.track_key and rating_count = 0;
  end if;
  if tg_op in ('INSERT', 'UPDATE') then
    insert into public.song_rating_totals (track_key, rating_count, rating_sum)
    values (new.track_key, 1, new.rating)
    on conflict (track_key) do update set
      rating_count = public.song_rating_totals.rating_count + 1,
      rating_sum = public.song_rating_totals.rating_sum + excluded.rating_sum;
    return new;
  end if;
  return old;
end;
$$;
revoke all on function private.update_song_rating_totals() from public;
create trigger song_rating_totals_changed
after insert or update or delete on public.song_ratings
for each row execute function private.update_song_rating_totals();

insert into public.song_rating_totals (track_key, rating_count, rating_sum)
select track_key, count(*)::integer, sum(rating)::integer
from public.song_ratings group by track_key;

create table public.song_streams (
  stream_id bigint generated by default as identity primary key,
  user_id uuid default auth.uid() references auth.users(id) on delete set null,
  track_key text not null check (length(track_key) > 0),
  song_id bigint references public.songs(song_id) on delete set null,
  streamed_at timestamptz not null default now()
);
create index song_streams_song_id_idx on public.song_streams(song_id);
alter table public.song_streams enable row level security;
create policy "Record own song stream" on public.song_streams for insert to authenticated
with check (user_id = (select auth.uid()));
grant insert on public.song_streams to authenticated;
grant usage, select on sequence public.song_streams_stream_id_seq to authenticated;

create table public.song_stream_totals (
  track_key text primary key,
  stream_count bigint not null default 0 check (stream_count >= 0)
);
alter table public.song_stream_totals enable row level security;
create policy "Read song stream totals" on public.song_stream_totals for select to authenticated using (true);
grant select on public.song_stream_totals to authenticated;

create function private.update_song_stream_totals() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.song_stream_totals (track_key, stream_count)
  values (new.track_key, 1)
  on conflict (track_key) do update
  set stream_count = public.song_stream_totals.stream_count + 1;
  return new;
end;
$$;
revoke all on function private.update_song_stream_totals() from public;
create trigger song_stream_totals_changed after insert on public.song_streams
for each row execute function private.update_song_stream_totals();
