alter table public.songs add column lyrics text;

create table public.song_comments (
  comment_id bigint generated by default as identity primary key,
  track_key text not null,
  song_id bigint references public.songs(song_id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  body text not null check (char_length(trim(body)) between 1 and 500),
  created_at timestamptz not null default now()
);

create index song_comments_track_created_idx on public.song_comments (track_key, created_at desc);
alter table public.song_comments enable row level security;
create policy "Read song comments" on public.song_comments for select to authenticated using (true);
create policy "Post own song comments" on public.song_comments for insert to authenticated
  with check ((select auth.uid()) = user_id);
grant select, insert on public.song_comments to authenticated;
grant usage, select on sequence public.song_comments_comment_id_seq to authenticated;
