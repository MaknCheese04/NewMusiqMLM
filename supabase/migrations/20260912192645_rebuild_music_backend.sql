create table public.artists (
  artist_id bigint generated by default as identity primary key,
  name text not null,
  created_at timestamptz not null default now()
);

create table public.albums (
  album_id bigint generated by default as identity primary key,
  name text not null,
  created_at timestamptz not null default now()
);

create table public.songs (
  song_id bigint generated by default as identity primary key,
  name text not null,
  created_at timestamptz not null default now()
);

create table public.genres (
  genre_id bigint generated by default as identity primary key,
  created_at timestamptz not null default now()
);

create table public.playlists (
  playlist_id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null,
  created_at timestamptz not null default now()
);

create table public.album_artists (
  album_artist_id bigint generated by default as identity primary key,
  album_id bigint references public.albums(album_id) on delete cascade,
  artist_id bigint references public.artists(artist_id) on delete cascade,
  created_at timestamptz not null default now()
);

create table public.album_songs (
  id bigint generated by default as identity primary key,
  album_id bigint references public.albums(album_id) on delete cascade,
  song_id bigint references public.songs(song_id) on delete cascade,
  created_at timestamptz not null default now()
);

create table public.song_artists (
  id bigint generated by default as identity primary key,
  song_id bigint not null references public.songs(song_id) on delete cascade,
  artist_id bigint not null references public.artists(artist_id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (song_id, artist_id)
);

create table public.playlist_songs (
  playlist_song_id bigint generated by default as identity primary key,
  playlist_id bigint references public.playlists(playlist_id) on delete cascade,
  song_id bigint references public.songs(song_id) on delete cascade,
  created_at timestamptz not null default now()
);

create index on public.playlists(user_id);
create index on public.album_artists(album_id);
create index on public.album_artists(artist_id);
create index on public.album_songs(album_id);
create index on public.album_songs(song_id);
create index on public.song_artists(song_id);
create index on public.song_artists(artist_id);
create index on public.playlist_songs(playlist_id);
create index on public.playlist_songs(song_id);

alter table public.artists enable row level security;
alter table public.albums enable row level security;
alter table public.songs enable row level security;
alter table public.genres enable row level security;
alter table public.playlists enable row level security;
alter table public.album_artists enable row level security;
alter table public.album_songs enable row level security;
alter table public.song_artists enable row level security;
alter table public.playlist_songs enable row level security;

create policy "Read artists" on public.artists for select to anon, authenticated using (true);
create policy "Read albums" on public.albums for select to anon, authenticated using (true);
create policy "Read songs" on public.songs for select to anon, authenticated using (true);
create policy "Read genres" on public.genres for select to anon, authenticated using (true);
create policy "Read album artists" on public.album_artists for select to anon, authenticated using (true);
create policy "Read album songs" on public.album_songs for select to anon, authenticated using (true);
create policy "Read song artists" on public.song_artists for select to anon, authenticated using (true);

create policy "Add artists" on public.artists for insert to authenticated with check (true);
create policy "Add albums" on public.albums for insert to authenticated with check (true);
create policy "Add songs" on public.songs for insert to authenticated with check (true);
create policy "Add album songs" on public.album_songs for insert to authenticated with check (true);
create policy "Add song artists" on public.song_artists for insert to authenticated with check (true);
create policy "Add album artists" on public.album_artists for insert to authenticated with check (true);

create policy "Read own playlists" on public.playlists for select to authenticated using (user_id = (select auth.uid()));
create policy "Create own playlists" on public.playlists for insert to authenticated with check (user_id = (select auth.uid()));
create policy "Read own playlist songs" on public.playlist_songs for select to authenticated using (exists (select 1 from public.playlists p where p.playlist_id = playlist_id and p.user_id = (select auth.uid())));
create policy "Add own playlist songs" on public.playlist_songs for insert to authenticated with check (exists (select 1 from public.playlists p where p.playlist_id = playlist_id and p.user_id = (select auth.uid())));

grant select on public.artists, public.albums, public.songs, public.genres, public.album_artists, public.album_songs, public.song_artists to anon, authenticated;
grant select, insert on public.playlists, public.playlist_songs to authenticated;
grant insert on public.artists, public.albums, public.songs, public.album_artists, public.album_songs, public.song_artists to authenticated;
grant usage, select on all sequences in schema public to authenticated;

